package ru.ttraum.kaop.runtime

/**
 * Declarations used only by code that the kaop compiler plugin generates. They are public because the generated
 * code lives in your modules, but they are not part of the API: they may change in any release (code compiled
 * with another kaop version must be recompiled), so using them by hand is a compile error.
 */
@RequiresOptIn(
    message = "Used only by code generated by the kaop compiler plugin; may change in any release.",
    level = RequiresOptIn.Level.ERROR,
)
@Retention(AnnotationRetention.BINARY)
@Target(AnnotationTarget.CLASS, AnnotationTarget.CONSTRUCTOR, AnnotationTarget.FUNCTION, AnnotationTarget.PROPERTY)
@MustBeDocumented
annotation class InternalKaopApi
