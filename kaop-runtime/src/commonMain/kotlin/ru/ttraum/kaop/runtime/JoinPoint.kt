package ru.ttraum.kaop.runtime

import kotlin.reflect.KClass
import kotlin.reflect.KType
import kotlin.reflect.typeOf

/** What every interceptor can see about the current invocation. */
sealed class AbstractJoinPoint(
    internal val advised: AdvisedMethod,
    /** `this` of the advised function (or its extension receiver), `null` for top-level functions. */
    val target: Any?,
    internal val arguments: Array<Any?>,
    internal val index: Int,
) {
    /** Metadata about the advised function. */
    val method: MethodSignature get() = advised.signature

    /** The annotation instance that bound the current interceptor (with its arguments). */
    val annotation: Annotation get() = advised.annotations[index]

    /**
     * Arguments of the current invocation (read-only — pass replacements to `proceed`).
     * Allocates a list view; prefer [argCount] / [arg] on hot paths.
     */
    val args: List<Any?> get() = arguments.asList()

    /** Number of arguments, without allocating. */
    val argCount: Int get() = arguments.size

    /**
     * The argument at [index] as [T], or `null` if it is `null` or not a [T] (`as? T`), without allocating.
     * `arg<Any>(i)` returns the argument untyped. Throws [IndexOutOfBoundsException] for an invalid [index].
     */
    inline fun <reified T> arg(index: Int): T? = argAt(index) as? T

    /**
     * The argument at [index] as [T], without allocating. Unlike [arg], a mismatch is an error: throws
     * [ClassCastException] naming the parameter and the actual type. A nullable [T] (`requireArg<String?>(i)`)
     * accepts `null`. Throws [IndexOutOfBoundsException] for an invalid [index].
     */
    inline fun <reified T> requireArg(index: Int): T {
        val value = argAt(index)
        if (value is T) return value
        throw ClassCastException(argTypeMismatch(index, value, typeOf<T>()))
    }

    @PublishedApi
    internal fun argAt(index: Int): Any? = arguments[index]

    // KType.toString() needs kotlin-reflect on the JVM; the classifier's simpleName works on every platform.
    @PublishedApi
    internal fun argTypeMismatch(index: Int, value: Any?, expected: KType): String {
        val expectedName = ((expected.classifier as? KClass<*>)?.simpleName ?: "$expected") +
            if (expected.isMarkedNullable) "?" else ""
        return "Argument #$index '${method.parameterNames[index]}' of ${method.qualifiedName} is " +
            "${if (value == null) "null" else value::class.simpleName}, expected $expectedName"
    }

    inline fun <reified A : Annotation> annotation(): A = annotation as A

    internal fun checkArity(newArgs: Array<out Any?>): Array<Any?> {
        require(newArgs.size == arguments.size) {
            "${method.qualifiedName} expects ${arguments.size} arguments, got ${newArgs.size}"
        }
        return arrayOf(*newArgs)
    }

    override fun toString(): String = "${this::class.simpleName}(${method.qualifiedName}, args=$args)"
}

/**
 * A single invocation of an advised regular function, as seen by one interceptor in the chain.
 *
 * Subclassed only by woven code: for every advised function and every interceptor in its chain the compiler
 * plugin generates a small final subclass whose [invokeNext] calls the next interceptor directly or runs the
 * original body. The JIT therefore always knows the exact class behind [proceed] — nothing goes through a call
 * site shared by all advised functions, and the whole chain can be inlined and scalar-replaced.
 */
abstract class JoinPoint @InternalKaopApi constructor(
    advised: AdvisedMethod,
    target: Any?,
    args: Array<Any?>,
    index: Int,
) : AbstractJoinPoint(advised, target, args, index) {
    /** Invokes the next interceptor, or the original function body, with the current arguments. */
    fun proceed(): Any? = invokeNext(target, arguments)

    /** Invokes the next interceptor, or the original function body, with replaced arguments. */
    fun proceed(vararg newArgs: Any?): Any? = invokeNext(target, checkArity(newArgs))

    /** Generated by the compiler plugin. */
    @InternalKaopApi
    protected abstract fun invokeNext(target: Any?, args: Array<Any?>): Any?
}

/** A single invocation of an advised `suspend` function, as seen by one interceptor in the chain. */
abstract class SuspendJoinPoint @InternalKaopApi constructor(
    advised: AdvisedMethod,
    target: Any?,
    args: Array<Any?>,
    index: Int,
) : AbstractJoinPoint(advised, target, args, index) {
    /** Invokes the next interceptor, or the original function body, with the current arguments. */
    suspend fun proceed(): Any? = invokeNext(target, arguments)

    /** Invokes the next interceptor, or the original function body, with replaced arguments. */
    suspend fun proceed(vararg newArgs: Any?): Any? = invokeNext(target, checkArity(newArgs))

    /** Generated by the compiler plugin. */
    @InternalKaopApi
    protected abstract suspend fun invokeNext(target: Any?, args: Array<Any?>): Any?
}

/** Static description of an advised function. */
class MethodSignature(
    val declaringClass: String?,
    val name: String,
    val parameterNames: List<String>,
    val returnType: String,
    val isSuspend: Boolean = false,
) {
    val qualifiedName: String get() = if (declaringClass == null) name else "$declaringClass.$name"

    override fun toString(): String =
        "${if (isSuspend) "suspend " else ""}$qualifiedName(${parameterNames.joinToString()}): $returnType"
}
